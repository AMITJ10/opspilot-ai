from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table,
    TableStyle
)

from src.ai.insights import generate_insights


def build_business_report(df, company_name):
    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=36,
        leftMargin=36,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    styles["Title"].alignment = TA_CENTER

    story = []

    story.append(Paragraph(
        "OpsPilot AI | Business Performance Report",
        styles["Title"]
    ))
    story.append(Spacer(1, 14))
    story.append(Paragraph(
        f"Company: {escape(company_name)}",
        styles["Heading2"]
    ))
    story.append(Spacer(1, 12))

    revenue = float(df["revenue"].sum())
    cost = float(df["cost"].sum())
    profit = float(df["profit"].sum())
    margin = profit / revenue * 100 if revenue else 0

    metrics = [
        ["Metric", "Value"],
        ["Total Revenue", f"INR {revenue:,.2f}"],
        ["Direct Cost", f"INR {cost:,.2f}"],
        ["Gross Profit", f"INR {profit:,.2f}"],
        ["Gross Margin", f"{margin:.2f}%"],
        ["Total Orders", str(len(df))]
    ]

    table = Table(metrics, colWidths=[240, 240])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#183153")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.whitesmoke, colors.white]),
        ("GRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
        ("TOPPADDING", (0, 0), (-1, -1), 9)
    ]))

    story.append(table)
    story.append(Spacer(1, 22))

    story.append(Paragraph(
        "Top Customers", styles["Heading2"]
    ))

    customers = (
        df.groupby("customer")["revenue"]
        .sum()
        .sort_values(ascending=False)
        .head(5)
    )

    for customer, value in customers.items():
        story.append(Paragraph(
            f"{escape(str(customer))}: INR {value:,.2f}",
            styles["BodyText"]
        ))
        story.append(Spacer(1, 5))

    story.append(Spacer(1, 16))
    story.append(Paragraph(
        "Automated Business Insights",
        styles["Heading2"]
    ))

    for insight in generate_insights(df):
        story.append(Paragraph(
            escape(str(insight)),
            styles["BodyText"]
        ))
        story.append(Spacer(1, 8))

    story.append(Spacer(1, 20))
    story.append(Paragraph(
        "Generated by OpsPilot AI. Financial values are "
        "calculated from the selected transaction data.",
        styles["Italic"]
    ))

    doc.build(story)
    buffer.seek(0)

    return buffer.getvalue()
